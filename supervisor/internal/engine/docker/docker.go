func (d *Docker) Networks(ctx context.Context, labels map[string]string) ([]engine.Network, error) {
	res, err := d.c.NetworkList(ctx, client.NetworkListOptions{Filters: labelFilters(labels)})
	if err != nil {
		return nil, err
	}
	var out []engine.Network
	for _, n := range res.Items {
		en := engine.Network{ID: n.ID, Name: n.Name, Labels: n.Labels}
		if len(n.IPAM.Config) > 0 && n.IPAM.Config[0].Subnet.IsValid() {
			en.Subnet = n.IPAM.Config[0].Subnet.String()
		}
		out = append(out, en)
	}
	return out, nil
}

func (d *Docker) Pull(ctx context.Context, ref string, progress func(engine.PullProgress)) error {
	resp, err := d.c.ImagePull(ctx, ref, client.ImagePullOptions{})
	if err != nil {
		return wrap(err)
	}
	defer resp.Close()
	// Per-layer progress, summed into one figure.
	type layer struct{ cur, total int64 }
	layers := map[string]layer{}
	for msg, err := range resp.JSONMessages(ctx) {
		if err != nil {
			return err
		}
		if msg.Error != nil {
			return errors.New(msg.Error.Message)
		}
		if msg.Progress != nil && msg.ID != "" && msg.Progress.Total > 0 {
			layers[msg.ID] = layer{msg.Progress.Current, msg.Progress.Total}
		}
		if progress != nil {
			p := engine.PullProgress{Status: msg.Status}
			for _, l := range layers {
				p.Current += l.cur
				p.Total += l.total
			}
			progress(p)
		}
	}
	return nil
}

func (d *Docker) ImageInspect(ctx context.Context, ref string) (engine.Image, error) {
	res, err := d.c.ImageInspect(ctx, ref)
	if err != nil {
		return engine.Image{}, wrap(err)
	}
	img := engine.Image{ID: res.ID}
	if res.Config != nil {
		img.Labels = res.Config.Labels
		img.User = res.Config.User
	}
	img.Arch = res.Architecture
	img.Size = res.Size
	if t, err := time.Parse(time.RFC3339Nano, res.Created); err == nil {
		img.Created = t
	}
	return img, nil
}

func (d *Docker) CopyFromImage(ctx context.Context, ref, path string) (io.ReadCloser, error) {
	created, err := d.c.ContainerCreate(ctx, client.ContainerCreateOptions{
		Config: &container.Config{Image: ref, Entrypoint: []string{"/bin/true"}},
	})
	if err != nil {
		return nil, wrap(err)
	}
	// With its volumes: a desktop image declares VOLUME /workspace, so each
	// copy would otherwise leave an anonymous volume behind.
	remove := func() {
		_, _ = d.c.ContainerRemove(context.WithoutCancel(ctx), created.ID, client.ContainerRemoveOptions{Force: true, RemoveVolumes: true})
	}
	res, err := d.c.CopyFromContainer(ctx, created.ID, client.CopyFromContainerOptions{SourcePath: path})
	if err != nil {
		remove()
		return nil, wrap(err)
	}
	return readCloser{res.Content, func() error { err := res.Content.Close(); remove(); return err }}, nil
}

func (d *Docker) CopyToContainer(ctx context.Context, id, dir string, archive io.Reader) error {
	_, err := d.c.CopyToContainer(ctx, id, client.CopyToContainerOptions{DestinationPath: dir, Content: archive})
	return wrap(err)
}

type readCloser struct {
	io.Reader
	close func() error
}

func (r readCloser) Close() error { return r.close() }

func (d *Docker) Events(ctx context.Context) (<-chan engine.Event, error) {
	f := client.Filters{}
	f.Add("type", "container")
	res := d.c.Events(ctx, client.EventsListOptions{Filters: f})
	out := make(chan engine.Event)
	go func() {
		defer close(out)
		for {
			select {
			case m, ok := <-res.Messages:
				if !ok {
					return
				}
				ev := engine.Event{ContainerID: m.Actor.ID, Action: string(m.Action), Labels: m.Actor.Attributes, Name: m.Actor.Attributes["name"]}
				select {
				case out <- ev:
				case <-ctx.Done():
					return
				}
			case <-res.Err:
				return
			case <-ctx.Done():
				return
			}
		}
	}()
	return out, nil
}

func (d *Docker) Info(ctx context.Context) (engine.HostInfo, error) {
	res, err := d.c.Info(ctx, client.InfoOptions{})
	if err != nil {
		return engine.HostInfo{}, err
	}
	return engine.HostInfo{CPUs: res.Info.NCPU, MemBytes: res.Info.MemTotal}, nil
}
