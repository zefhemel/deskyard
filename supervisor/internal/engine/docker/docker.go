// The seccomp profile desktops need for Flatpak's sandbox (bubblewrap):
// Docker's default plus the namespace syscalls. Generated by
// scripts/gen-seccomp.py.
//
//go:embed flatpak-seccomp.json
var flatpakSeccomp string

type Docker struct {
	c *client.Client
}

var _ engine.Engine = (*Docker)(nil)

// New connects to host (a DOCKER_HOST-style address), or the environment's
// default when host is empty.
func New(host string) (*Docker, error) {
	opts := []client.Opt{client.FromEnv, client.WithAPIVersionNegotiation()}
	if host != "" {
		opts = append(opts, client.WithHost(host))
	}
	c, err := client.New(opts...)
	if err != nil {
		return nil, err
	}
	return &Docker{c: c}, nil
}

func wrap(err error) error {
	if err != nil && errdefs.IsNotFound(err) {
		return fmt.Errorf("%w: %v", engine.ErrNotFound, err)
	}
	return err
}

var port8080 = network.MustParsePort("8080/tcp")

func (d *Docker) Create(ctx context.Context, s engine.ContainerSpec) (string, error) {
	if s.NetworkContainer != "" && (s.Network != "" || len(s.Aliases) != 0) {
		return "", errors.New("shared network namespace cannot attach networks or aliases")
	}
	for _, m := range s.Mounts {
		if !m.MustExist || !m.ReadOnly {
			continue
		}
		ping, err := d.c.Ping(ctx, client.PingOptions{NegotiateAPIVersion: true})
		if err != nil {
			return "", wrap(err)
		}
		if ping.APIVersion == "" || versions.LessThan(ping.APIVersion, "1.44") || versions.LessThan(d.c.ClientVersion(), "1.44") {
			return "", fmt.Errorf("host folders require Docker API 1.44 or newer for recursive read-only mounts")
		}
		break
	}
	env := make([]string, 0, len(s.Env))
	for k, v := range s.Env {
		env = append(env, k+"="+v)
	}
	sort.Strings(env)
	cfg := &container.Config{
		Image:        s.Image,
		Env:          env,
		Labels:       s.Labels,
		Cmd:          s.Cmd,
		Entrypoint:   s.Entrypoint,
		ExposedPorts: network.PortSet{port8080: {}},
	}
	if s.NetworkContainer != "" {
		cfg.ExposedPorts = nil
	}
	if s.NoHealthcheck {
		cfg.Healthcheck = &container.HealthConfig{Test: []string{"NONE"}}
	}
	hc := &container.HostConfig{
		ShmSize: s.ShmBytes,
		CapAdd:  s.CapAdd,
		Resources: container.Resources{
			Memory:   s.MemoryBytes,
			NanoCPUs: s.NanoCPUs,
		},
	}
	for _, d := range s.Devices {
		hc.Devices = append(hc.Devices, container.DeviceMapping{PathOnHost: d, PathInContainer: d, CgroupPermissions: "rwm"})
	}
	if s.Restart != "" {
		hc.RestartPolicy = container.RestartPolicy{Name: container.RestartPolicyMode(s.Restart)}
	}
	for _, m := range s.Mounts {
		if m.MustExist {
			hc.Mounts = append(hc.Mounts, mount.Mount{Type: mount.TypeBind, Source: m.Source, Target: m.Target, ReadOnly: m.ReadOnly, BindOptions: &mount.BindOptions{ReadOnlyForceRecursive: m.ReadOnly}})
			continue
		}
		bind := m.Source + ":" + m.Target
		if m.ReadOnly {
			bind += ":ro"
		}
		hc.Binds = append(hc.Binds, bind)
	}
	if s.Flatpak {
		hc.SecurityOpt = []string{"seccomp=" + flatpakSeccomp, "apparmor=unconfined"}
		// The CLI's --security-opt systempaths=unconfined: no masked or
		// read-only /proc and /sys paths (empty lists, not nil, override the defaults).
		hc.MaskedPaths = []string{}
		hc.ReadonlyPaths = []string{}
	}
	if s.NoNewPrivileges {
		hc.SecurityOpt = append(hc.SecurityOpt, "no-new-privileges=true")
	}
	if s.NetworkContainer != "" {
		hc.NetworkMode = container.NetworkMode("container:" + s.NetworkContainer)
	}
	var nc *network.NetworkingConfig
	if s.Network != "" {
		hc.NetworkMode = container.NetworkMode(s.Network)
		nc = &network.NetworkingConfig{EndpointsConfig: map[string]*network.EndpointSettings{
			s.Network: {Aliases: s.Aliases},
		}}
	}
	res, err := d.c.ContainerCreate(ctx, client.ContainerCreateOptions{
		Name: s.Name, Config: cfg, HostConfig: hc, NetworkingConfig: nc,
	})
	if err != nil {
		return "", wrap(err)
	}
	return res.ID, nil
}

func (d *Docker) Start(ctx context.Context, id string) error {
	_, err := d.c.ContainerStart(ctx, id, client.ContainerStartOptions{})
	return wrap(err)
}

func seconds(t time.Duration) *int {
	s := int(t / time.Second)
	return &s
}

