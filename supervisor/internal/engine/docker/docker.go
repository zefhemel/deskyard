func (d *Docker) Inspect(ctx context.Context, id string) (engine.Container, error) {
	res, err := d.c.ContainerInspect(ctx, id, client.ContainerInspectOptions{})
	if err != nil {
		return engine.Container{}, wrap(err)
	}
	r := res.Container
	c := engine.Container{
		ID:      r.ID,
		Name:    strings.TrimPrefix(r.Name, "/"),
		ImageID: r.Image,
		Env:     map[string]string{},
		IP:      map[string]string{},
	}
	if r.Config != nil {
		c.Image = r.Config.Image
		c.Labels = r.Config.Labels
		for _, kv := range r.Config.Env {
			k, v, _ := strings.Cut(kv, "=")
			c.Env[k] = v
		}
	}
	if r.State != nil {
		if r.State.Health != nil {
			c.Health = string(r.State.Health.Status)
		}
		c.State = string(r.State.Status)
		c.Error = r.State.Error
		if t, err := time.Parse(time.RFC3339Nano, r.State.StartedAt); err == nil {
			c.StartedAt = t
		}
	}
	if r.HostConfig != nil {
		if owner, ok := strings.CutPrefix(string(r.HostConfig.NetworkMode), "container:"); ok {
			c.NetworkContainer = owner
		}
		c.Restart = string(r.HostConfig.RestartPolicy.Name)
		c.MemoryBytes = r.HostConfig.Memory
		c.NanoCPUs = r.HostConfig.NanoCPUs
		for _, d := range r.HostConfig.Devices {
			c.Devices = append(c.Devices, d.PathOnHost)
		}
	}
	for _, m := range r.Mounts {
		em := engine.Mount{Source: m.Source, OnEngineHost: true, Target: m.Destination, ReadOnly: !m.RW}
		if m.Type == mount.TypeVolume {
			em.Volume = m.Name
		}
		c.Mounts = append(c.Mounts, em)
	}
	if r.NetworkSettings != nil {
		for name, ep := range r.NetworkSettings.Networks {
			if ep != nil && ep.IPAddress.IsValid() {
				c.IP[name] = ep.IPAddress.String()
			}
		}
	}
	return c, nil
}

func labelFilters(labels map[string]string) client.Filters {
	f := client.Filters{}
	for k, v := range labels {
		if v == "" {
			f.Add("label", k)
		} else {
			f.Add("label", k+"="+v)
		}
	}
	return f
}

func (d *Docker) List(ctx context.Context, labels map[string]string) ([]engine.Container, error) {
	res, err := d.c.ContainerList(ctx, client.ContainerListOptions{All: true, Filters: labelFilters(labels)})
	if err != nil {
		return nil, err
	}
	out := make([]engine.Container, 0, len(res.Items))
	for _, s := range res.Items {
		c, err := d.Inspect(ctx, s.ID)
		if errors.Is(err, engine.ErrNotFound) {
			continue // removed meanwhile
		}
		if err != nil {
			return nil, err
		}
		out = append(out, c)
	}
	return out, nil
}

func (d *Docker) Exec(ctx context.Context, id string, s engine.ExecSpec) (*engine.Process, error) {
	ctx, cancel := context.WithCancel(ctx)
	opts := client.ExecCreateOptions{
		User: s.User, WorkingDir: s.WorkDir, Env: s.Env, Cmd: s.Cmd, TTY: s.Tty,
		AttachStdin: s.Stdin, AttachStdout: true, AttachStderr: true,
	}
	if s.Tty && s.Cols > 0 && s.Rows > 0 {
		opts.ConsoleSize = client.ConsoleSize{Height: s.Rows, Width: s.Cols}
	}
	created, err := d.c.ExecCreate(ctx, id, opts)
	if err != nil {
		cancel()
		return nil, wrap(err)
	}
	att, err := d.c.ExecAttach(ctx, created.ID, client.ExecAttachOptions{TTY: s.Tty, ConsoleSize: opts.ConsoleSize})
	if err != nil {
		cancel()
		return nil, wrap(err)
	}
	var stdin io.WriteCloser = closeWriter{att.Conn}
	if s.Tty {
		// Half-closing a TTY exec's connection ends its output too; a
		// terminal's end of input is Ctrl-D.
		stdin = ttyStdin{att.Conn}
	}
	p := &engine.Process{
		Stdin: stdin,
		Resize: func(cols, rows uint) error {
			_, err := d.c.ExecResize(ctx, created.ID, client.ExecResizeOptions{Height: rows, Width: cols})
			return err
		},
	}
	var readers []*io.PipeReader

	if s.Tty {
		p.Stdout = att.Reader
	} else {
		outR, outW := io.Pipe()
		errR, errW := io.Pipe()
		readers = []*io.PipeReader{outR, errR}
		go func() {
			_, err := stdcopy.StdCopy(outW, errW, att.Reader)
			outW.CloseWithError(err)
			errW.CloseWithError(err)
		}()
		p.Stdout, p.Stderr = outR, errR

	}
	closeProcess := sync.OnceFunc(func() {
		cancel()
		att.Close()
		for _, reader := range readers {
			_ = reader.Close()
		}
	})
	stop := context.AfterFunc(ctx, closeProcess)
	p.Close = func() { stop(); closeProcess() }

	p.Wait = func() (int, error) { return d.waitExec(ctx, created.ID) }
	return p, nil
}

func (d *Docker) waitExec(ctx context.Context, id string) (int, error) {
	for {
		res, err := d.c.ExecInspect(ctx, id, client.ExecInspectOptions{})
		if err != nil {
			return -1, err
		}
		if !res.Running {
			return res.ExitCode, nil
		}
		select {
		case <-ctx.Done():
			return -1, ctx.Err()
		case <-time.After(50 * time.Millisecond):
		}
	}
}

// closeWriter closes only the write half of the hijacked connection, so the
// command sees end of input while its output keeps flowing.
type closeWriter struct{ conn io.Writer }

func (w closeWriter) Write(b []byte) (int, error) { return w.conn.Write(b) }
func (w closeWriter) Close() error {
	if cw, ok := w.conn.(interface{ CloseWrite() error }); ok {
		return cw.CloseWrite()
	}
	return nil
}

type ttyStdin struct{ conn io.Writer }

func (w ttyStdin) Write(b []byte) (int, error) { return w.conn.Write(b) }
func (w ttyStdin) Close() error {
	_, err := w.conn.Write([]byte{4})
	return err
}

func (d *Docker) Top(ctx context.Context, id string, args string) ([]string, [][]string, error) {
	res, err := d.c.ContainerTop(ctx, id, client.ContainerTopOptions{Arguments: strings.Fields(args)})
	if err != nil {
		return nil, nil, wrap(err)
	}
	return res.Titles, res.Processes, nil
}

func (d *Docker) Stats(ctx context.Context, id string) (<-chan engine.Stats, error) {
	res, err := d.c.ContainerStats(ctx, id, client.ContainerStatsOptions{Stream: true})
	if err != nil {
		return nil, wrap(err)
	}
	out := make(chan engine.Stats)
	go func() {
		defer close(out)
		defer res.Body.Close()
		dec := json.NewDecoder(res.Body)
		for {
			var s container.StatsResponse
			if err := dec.Decode(&s); err != nil {
				return
			}
			st := engine.Stats{Time: s.Read, OnlineCPUs: int(s.CPUStats.OnlineCPUs), MemLimit: s.MemoryStats.Limit}
			cpuDelta := float64(s.CPUStats.CPUUsage.TotalUsage) - float64(s.PreCPUStats.CPUUsage.TotalUsage)
			sysDelta := float64(s.CPUStats.SystemUsage) - float64(s.PreCPUStats.SystemUsage)
			if cpuDelta > 0 && sysDelta > 0 {
				st.CPUPercent = cpuDelta / sysDelta * float64(s.CPUStats.OnlineCPUs) * 100
			}
			// Usage minus page cache, as `docker stats` reports it.
			st.MemBytes = s.MemoryStats.Usage
			if inactive, ok := s.MemoryStats.Stats["inactive_file"]; ok && inactive < st.MemBytes {
				st.MemBytes -= inactive
			}
			select {
			case out <- st:
			case <-ctx.Done():
				return
			}
		}
	}()
	return out, nil
}

func (d *Docker) CreateNetwork(ctx context.Context, name, subnet string, labels map[string]string) error {
	opts := client.NetworkCreateOptions{Driver: "bridge", Labels: labels}
	if subnet != "" {
		p, err := netip.ParsePrefix(subnet)
		if err != nil {
			return err
		}
		opts.IPAM = &network.IPAM{Config: []network.IPAMConfig{{Subnet: p}}}
	}
	_, err := d.c.NetworkCreate(ctx, name, opts)
	if err != nil && strings.Contains(err.Error(), "Pool overlaps") {
		return fmt.Errorf("%w: %w", engine.ErrSubnetTaken, err)
	}
	return err
}

